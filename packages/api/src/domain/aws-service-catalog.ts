function entry(id: string, name: string, category: string): AwsServiceCatalogEntry {
  return {
    id,
    name,
    category,
    icon: SERVICE_ICONS[id] || CATEGORY_ICON[category] || 'square',
    implemented: IMPLEMENTED_IDS.has(id),
  };
}

